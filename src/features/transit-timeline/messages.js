export function translator(messages = {}) {
  const dictionary = { ...en, ...messages };
  return (key, values = {}) => String(dictionary[key] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
