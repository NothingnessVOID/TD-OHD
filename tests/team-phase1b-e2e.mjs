import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { PROFILE_STORAGE_KEY } from '../src/lib/profile-storage.js';

const browser = await chromium.launch({ channel: process.env.CHROME_CHANNEL || 'chromium', headless: true });
const base = process.env.E2E_URL || 'http://127.0.0.1:5174';
const profiles = Array.from({ length: 6 }, (_, i) => ({ id: `team-test-${i}`, name: i < 2 ? 'Same name' : `Person ${i}`, birthDate: `${1990 + i}-04-15`, birthTime: '12:00', timeUnknown: false, location: { timezone: 0, lat: null, lon: null, iana: null, name: null } }));
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'en-US' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.addInitScript(({ key, profiles }) => { localStorage.setItem('ohd-language', 'en'); localStorage.setItem(key, JSON.stringify(profiles)); localStorage.setItem('ohd-last-person-id', profiles[0].id); }, { key: PROFILE_STORAGE_KEY, profiles });
  await page.goto(base);
  // Ensure the persisted person has finished booting before opening Team.
  await page.locator('#chart-view:not(.hidden)').waitFor({ timeout: 120000 });
  await page.locator('#mobile-menu-toggle').click();
  await page.locator('.nav-link[data-view="team"]').click();
  await page.locator('.team-advanced > summary').click();
  await page.locator('#team-view:not(.hidden) .team-pool summary').click();
  await page.locator('#team-view:not(.hidden) #team-person-picker').waitFor();
  const add = async id => { await page.locator('#team-person-picker').selectOption(id); await page.locator('#team-add-person').click(); };
  await add(profiles[0].id);
  await add(profiles[1].id);
  assert.equal(await page.locator('.team-member-card').count(), 2);
  await page.locator('#team-group-new').click();
  await page.locator('#team-calculate').click();
  assert.match(await page.locator('#team-content').innerText(), /three members/);
  await add(profiles[2].id);
  await add(profiles[2].id);
  assert.equal(await page.locator('.team-member-card').count(), 3);
  assert.match(await page.locator('#team-content').innerText(), /already in this team/);
  await page.locator('#team-name').fill('<Team & friends>');
  await page.locator('#team-save').click();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('ohd-teams-v1')));
  assert.equal(stored.teams[0].schemaVersion, 2);
  assert.equal(stored.teams[0].kind, 'penta');
  assert.equal(stored.teams[0].members.length, 3);
  assert.equal(JSON.stringify(stored).includes('birthDate'), false);
  assert.equal(JSON.stringify(stored).includes('chart'), false);
  assert.equal(await page.locator('#team-selected').locator('script').count(), 0);
  for (const card of await page.locator('.team-member-card').all()) await card.locator('.team-assign').click();
  await page.locator('#team-calculate').click();
  await page.locator('.penta-overview').waitFor({ timeout: 60000 });
  assert.equal(await page.locator('.team-channel').count(), 6);
  assert.equal(await page.locator('.penta-gate').count(), 12);
  assert.doesNotMatch(await page.locator('#team-content').innerText(), /Team Roles|Recommendations|Group Type/);
  const before = stored.teams[0].members.map(m => m.memberId);
  await page.reload();
  await page.locator('#chart-view:not(.hidden)').waitFor({ timeout: 120000 });
  await page.locator('#mobile-menu-toggle').click();
  await page.locator('.nav-link[data-view="team"]').click();
  await page.locator('.team-advanced > summary').click();
  await page.locator('#team-view:not(.hidden) #team-list').waitFor();
  await page.locator('#team-list').selectOption(stored.teams[0].teamId);
  assert.equal(await page.locator('.team-member-card').count(), 3);
  await page.locator('.team-pool summary').click();
  for (const card of await page.locator('.team-member-card').all()) await card.locator('.team-assign').click();
  assert.deepEqual((await page.evaluate(() => JSON.parse(localStorage.getItem('ohd-teams-v1')))).teams[0].members.map(m => m.memberId), before);
  await page.locator('#add-member').click();
  const row = page.locator('.team-member-row').first();
  assert.equal(await row.locator('.team-time').inputValue(), '');
  await row.locator('.team-name').fill('Quick');
  await page.locator('#team-save').click();
  assert.match(await page.locator('#team-content').innerText(), /Unsaved members: Quick/);
  await page.locator('#team-calculate').click();
  assert.match(await page.locator('#team-content').innerText(), /Birth details need correction: Quick/);
  await row.locator('.team-date').fill('2000-02-29');
  await row.locator('.team-time').fill('10:00');
  await row.locator('.ps-toggle').click();
  await row.locator('.ps-manual').fill('0');
  const profileBefore = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, PROFILE_STORAGE_KEY);
  await row.locator('.team-assign-quick').click();
  assert.equal(await page.locator('.team-group-member').count(), 4);
  await page.locator('#team-calculate').click();
  if (await page.locator('#team-content [role="alert"]').count()) throw new Error(await page.locator('#team-content').innerText());
  await page.locator('.penta-overview').waitFor({ timeout: 60000 });
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, PROFILE_STORAGE_KEY), profileBefore);
  await page.locator('#team-save').click();
  assert.match(await page.locator('#team-content').innerText(), /Unsaved members: Quick/);
  await row.locator('.team-save-person').click();
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, PROFILE_STORAGE_KEY), profileBefore + 1);
  await page.locator('#team-save').click();
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('ohd-teams-v1')))).teams[0].members.length, 4);
  await page.locator('#more-toggle').click();
  await page.locator('#language-menu summary').click();
  await page.locator('[data-language="zh-Hant"]').click();
  assert.equal(await page.locator('#team-name').inputValue(), '<Team & friends>');
  assert.equal(await page.locator('.team-member-card').count(), 4);
  const horizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2);
  assert.equal(horizontalOverflow, false, '390px viewport has no horizontal scroll');
  await page.locator('#language-menu summary').click();
  await page.locator('[data-language="zh-CN"]').click();
  assert.equal(await page.locator('.team-member-card').count(), 4);
  assert.deepEqual(errors, []);
  console.log('Team Phase 1B browser smoke passed: identity, save/reload, quick input, Penta, languages and 390px.');
} finally { await browser.close(); }
